    /// The preshared dictionary must at least halve the size of a
    /// representative corpus, must keep every variant near or below its raw
    /// postcard size, and must never make a variant worse than plain deflate
    /// without the dictionary.
    #[test]
    fn dictionary_compresses_representative_corpus() {
        let corpus = representative_corpus();
        let raw_total: usize = corpus.iter().map(|(_, b)| b.len()).sum();
        let comp_total: usize = corpus.iter().map(|(_, b)| compress(b).len()).sum();

        // Diagnostic table (visible with --nocapture).
        for (name, raw) in &corpus {
            let c = compress(raw).len();
            println!(
                "{name:<22} raw {:>5}  comp {:>5}  ratio {:>5.2}",
                raw.len(),
                c,
                raw.len() as f64 / c as f64
            );
        }
        println!(
            "TOTAL raw {raw_total} comp {comp_total} ratio {:.2}",
            raw_total as f64 / comp_total as f64
        );

        // ≥2× aggregate compression.
        assert!(
            comp_total * 2 <= raw_total,
            "expected ≥2× compression: raw {raw_total} → compressed {comp_total} \
             ({:.2}×)",
            raw_total as f64 / comp_total as f64
        );

        // No variant blows up.  Hash-only and unit variants are
        // incompressible (their payloads are blake3/ed25519 randomness), so
        // deflate's irreducible framing overhead (~8 bytes) is allowed; a
        // larger delta means the dictionary actively hurt that variant.
        for (name, raw) in &corpus {
            let c = compress(raw).len();
            assert!(
                c <= raw.len() + 8,
                "{name}: compressed {c} bytes > raw {} bytes + 8 slack",
                raw.len()
            );
        }

        // The dictionary must never make a variant worse than plain deflate
        // (no preshared dictionary) would.
        for (name, raw) in &corpus {
            let with_dict = compress(raw).len();
            let without = compress_impl(raw, None).len();
            assert!(
                with_dict <= without,
                "{name}: dictionary preset made compression worse \
                 ({with_dict} > {without})"
            );
        }
    }

