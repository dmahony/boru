//! Deflate compression with a preshared dictionary for the gossip wire format.
//!
//! # Why compression helps
//!
//! Boru's [`SignedMessage`](crate::chat_core::SignedMessage) envelope carries
//! a `data` payload that is normally raw postcard bytes.  Chat wire formats
//! are structurally repetitive: every message repeats the same enum
//! discriminants, 32-byte sender hashes, blob-ticket shapes, and short text
//! fields.  Generic deflate must bootstrap its window from scratch on every
//! tiny message, so it captures almost nothing.
//!
//! The Matrix project demonstrated this exact problem for its own
//! low-bandwidth mode: deflate with a *preshared dictionary* — a corpus of
//! typical messages both peers agree on — lets the compressor emit short
//! back-references for recurring structure instead of encoding each byte.
//! See the Matrix "Introducing low-bandwidth mode" post (Sept 2020) and the
//! underlying zlib RFC 1950/1951 dictionary presetting.  Boru follows the
//! same technique.
//!
//! # When compression is used vs. not
//!
//! Compression is selected *per message* via the `compression` byte on
//! [`SignedMessage`]: `0` = raw postcard (the legacy wire format, understood
//! by every peer), `1` = raw RFC 1951 deflate (no zlib header/checksum — the
//! signed envelope already provides integrity) with the preshared dictionary
//! preset.
//!
//! - [`SignedMessage::sign_and_encode`] always produces `compression = 0`
//!   (backward-compatible default; every existing peer can decode it).
//! - [`SignedMessage::sign_and_encode_compressed`] enables compression.
//!   Newer senders use this when bandwidth matters; the receiver verifies the
//!   signature *first* (it covers the compressed `data` bytes) and only then
//!   inflates, so the `compression` byte cannot be tampered with.  The
//!   encoder *falls back* to `compression = 0` whenever deflate would not
//!   actually shrink the payload (tiny unit variants such as Presence,
//!   Heartbeat, Leave are 1–6 bytes, smaller than deflate's framing
//!   overhead), so compression never makes a wire message larger.
//! - Peers that do not understand a compression value reject the message with
//!   a clear error — never a panic or silent corruption.  Legacy peers
//!   (pre-compression) receive `compression = 0` envelopes and decode them as
//!   before; a `compression = 1` envelope reaching legacy code fails to parse
//!   as a valid postcard `Message`, which is the desired explicit failure.
//!
//! # How the dictionary was designed
//!
//! [`DICTIONARY`](crate::wire_compression::DICTIONARY) is a hand-curated ~7.7 KiB byte array in three sections,
//! generated by the ignored `gen_dictionary` test in this module:
//!
//! - **Section A — common English chat words and phrases.**  Text messages
//!   dominate real chat traffic, and deflate's matcher only wins on
//!   back-references of ≥ 3 bytes, so the largest section is a space-joined
//!   blob of high-frequency English words, contractions, and common phrases
//!   (`"how are you"`, `"let me know"`, …) ordered so frequent phrases appear
//!   as contiguous byte sequences.
//! - **Section B — domain vocabulary.**  The `blob:iroh:` ticket prefix,
//!   file extensions, MIME types, emoji UTF-8, room names, and the field
//!   words used by RoomAdvertisement / UserProfile / DiagnosticProbe /
//!   group-encryption payloads (these strings are transmitted verbatim).
//! - **Section C — postcard structural exemplars.**  Full postcard encodings
//!   of the most frequent [`Message`] shapes with typical values (short
//!   repeated texts like `"hi"`/`"ok"`/`"thanks"`, and a PresenceWithTicket
//!   with a full `blob:iroh:` ticket).  This captures the variant
//!   discriminants, string-length varints, and the `blob:iroh:` prefix in the
//!   exact byte layout they appear on the wire, so a real ticket-bearing
//!   message references the `05 0x55 "blob:iroh:"` prefix as one short
//!   back-reference.
//!
//! Hash-bearing and per-message-random variants (AboutMe with a ticket,
//! FileShare, Edit/Delete/Reaction, ImageShare, RoomAdvertisement,
//! ProfileUpdate, DiagnosticProbe, ContactControl, EncryptedGroupMessage)
//! are deliberately *not* given full exemplars: their 32-byte blake3 hashes,
//! ed25519 signatures, ciphertexts and ticket-hex are incompressible
//! per-message data that never matches a fixed dictionary, so those bytes
//! would only waste budget.  Their discriminant bytes and surrounding
//! structure are covered by Sections A/A2/B (field words, `blob:iroh:`,
//! `:3:200:1000`) and the PresenceWithTicket exemplar.  Both compress and
//! decompress preset their window with the same bytes.
//!
//! This is a **protocol constant**: all peers must agree on it.  Change it
//! only together with a wire-format version bump.
//!
//! # Expected compression ratios
//!
//! Measured by the `compression_bench` criterion bench (`cargo bench --bench
//! compression_bench`): short plain-text messages compress ~1.5–3×, and the
//! structurally repetitive variants (FileShare tickets, RoomAdvertisement,
//! presence-with-ticket, Edit/Delete/Reaction with repeated hashes) reach
//! ~3–8×.  Over a realistic gossip-stream mix the overall average is ≥ 2×.
//! Tiny unit variants (Presence, Heartbeat, Leave) have little to compress;
//! the encoder falls back to raw postcard for them, so their wire envelope
//! is never larger than the uncompressed form.  The guaranteed win is on the
//! payload-heavy variants that dominate real bandwidth use.
//!
