/// Compress `data` with deflate using the preshared [`DICTIONARY`].
///
/// The returned bytes are a self-contained raw deflate stream that
/// [`decompress`] can inflate.  Infallible for any input.
pub fn compress(data: &[u8]) -> Vec<u8> {
    compress_impl(data, Some(DICTIONARY))
}

fn compress_impl(data: &[u8], dictionary: Option<&[u8]>) -> Vec<u8> {
    let mut encoder = Compress::new_with_window_bits(Compression::default(), false, WINDOW_BITS);
    if let Some(dict) = dictionary {
        encoder
            .set_dictionary(dict)
            .expect("preshared dictionary fits the deflate window");
    }
    let mut out = Vec::with_capacity(data.len().saturating_add(data.len() / 8).max(64));
    let mut buf = [0u8; 4096];
    let mut offset = 0usize;
    let mut done = false;
    while !done {
        let out_before = encoder.total_out();
        let status = encoder
            .compress(&data[offset..], &mut buf, FlushCompress::None)
            .expect("deflate compression is infallible");
        out.extend_from_slice(&buf[..(encoder.total_out() - out_before) as usize]);
        offset = encoder.total_in() as usize;
        if status == Status::StreamEnd {
            done = true;
        } else if offset >= data.len() {
            // All input consumed but the stream is not finished — flush it.
            let out_before = encoder.total_out();
            let status = encoder
                .compress(&[], &mut buf, FlushCompress::Finish)
                .expect("deflate finish is infallible");
            out.extend_from_slice(&buf[..(encoder.total_out() - out_before) as usize]);
            done = status == Status::StreamEnd;
        }
    }
    out
}

/// Inflate a deflate stream produced by [`compress`] with the preshared
/// [`DICTIONARY`].
///
/// Returns a clear error (never panics) on malformed or truncated input, and
/// refuses to expand beyond `MAX_DECOMPRESSED_SIZE` bytes.
pub fn decompress(data: &[u8]) -> Result<Vec<u8>> {
    let mut decoder = Decompress::new_with_window_bits(false, WINDOW_BITS);
    decoder
        .set_dictionary(DICTIONARY)
        .expect("preshared dictionary fits the inflate window");
    let mut out = Vec::with_capacity(
        data.len()
            .saturating_mul(4)
            .min(MAX_DECOMPRESSED_SIZE)
            .max(64),
    );
    let mut buf = vec![0u8; 4096];
    let mut offset = 0usize;
    loop {
        let in_before = decoder.total_in();
        let out_before = decoder.total_out();
        let status = decoder
            .decompress(&data[offset..], &mut buf, FlushDecompress::None)
            .std_context("inflate failed")?;
        let produced = (decoder.total_out() - out_before) as usize;
        if out.len() + produced > MAX_DECOMPRESSED_SIZE {
            bail_any!("decompressed message exceeds {MAX_DECOMPRESSED_SIZE} bytes");
        }
        out.extend_from_slice(&buf[..produced]);
        offset = decoder.total_in() as usize;
        match status {
            Status::StreamEnd => return Ok(out),
            Status::BufError => {
                // zlib reports `BufError` both when the output buffer is full
                // *and* when no progress is possible (input exhausted
                // mid-stream).  The latter is a truncated stream — without
                // this guard the loop would grow the buffer forever.
                if decoder.total_in() == in_before && decoder.total_out() == out_before {
                    bail_any!("truncated or corrupt deflate stream (no progress)");
                }
                buf = vec![0u8; buf.len().saturating_mul(2).min(MAX_DECOMPRESSED_SIZE)];
            }
            Status::Ok => {
                if offset >= data.len() {
                    bail_any!("truncated deflate stream");
                }
            }
        }
    }
}

