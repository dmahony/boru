/// Log2 of the deflate window size (32 KiB).  Messages are small, but a
/// larger window costs nothing and keeps the dictionary fully addressable.
const WINDOW_BITS: u8 = 15;

/// Hard cap on decompressed payload size (64 MiB) so a hostile peer cannot
/// send a tiny deflate bomb that exhausts memory.  Real boru messages are
/// orders of magnitude smaller.
const MAX_DECOMPRESSED_SIZE: usize = 64 * 1024 * 1024;

